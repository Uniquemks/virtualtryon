export const getWardrobeItems = (category) => {
  return WARDROBE_REGISTRY[category] || [];
};

export const getThumbnail = (itemId) => {
  for (const category in WARDROBE_REGISTRY) {
    const item = WARDROBE_REGISTRY[category].find(i => i.id === itemId);
    if (item) return item.thumbnail;
  }
  return null;
};

export const getDrapingAssets = (itemId, size = 'normal') => {
  for (const category in WARDROBE_REGISTRY) {
    const item = WARDROBE_REGISTRY[category].find(i => i.id === itemId);
    if (item) {
      // Basic size resolution logic: filter assets by size keyword if applicable
      // This is a future-proof resolver that can be expanded
      const matchedAssets = item.assets.filter(asset => asset.includes(size));
      return matchedAssets.length > 0 ? matchedAssets : item.assets;
    }
  }
  return [];
};
